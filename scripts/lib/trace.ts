import fs from "node:fs";
import path from "node:path";

/**
 * Requirement tracing helpers. They read requirement IDs from `docs/SPEC.md`,
 * look for tests whose names start with those IDs, and render the table kept in
 * `docs/requirements-trace.md`. Used by `scripts/trace.ts` and by `tests/docs.test.ts`.
 */

export interface Requirement {
  id: string;
  /** First sentence of the requirement text. */
  text: string;
}

export interface TraceRow extends Requirement {
  tests: string[];
  screen: string;
}

/**
 * These IDs are verified by the build pipeline and by documents, not by unit
 * tests, so a missing test name is not an error for them.
 */
export const PIPELINE_VERIFIED_IDS: readonly string[] = [
  "REL-1",
  "REL-2",
  "REL-3",
  "REL-5",
  "REL-7",
];

const SCREEN_BY_PREFIX: Record<string, string> = {
  AUTH: "Setup, Login",
  INV: "Inventory",
  SUP: "Suppliers",
  SAL: "Sales",
  DASH: "Dashboard",
  REP: "Reports",
  REL: "None (release pipeline)",
};

const SCREEN_BY_ID: Record<string, string> = {
  "AUTH-1": "Setup",
  "AUTH-2": "Login",
  "AUTH-3": "All screens (session check in the main process)",
  "AUTH-5": "Login",
  "REL-4": "Setup, Login",
  "REL-6": "None (repository test)",
};

const TEST_DIRECTORIES = ["src", "scripts", "tests"];
const TEST_FILE = /\.test\.(ts|tsx)$/;
const TEST_NAME = /\b(?:it|test)(?:\.\w+)*\s*\(\s*(["'`])\s*([A-Z]+-\d+)\b/g;

/** Reads `- **ABC-1** text` lines from the specification. */
export function parseRequirements(specText: string): Requirement[] {
  const requirements: Requirement[] = [];
  const pattern = /^- \*\*([A-Z]+-\d+)\*\*\s+(.+)$/gm;
  let match: RegExpExecArray | null;
  while ((match = pattern.exec(specText)) !== null) {
    const id = match[1];
    const body = match[2];
    if (id === undefined || body === undefined) continue;
    const sentence = /^.*?[.!?](?=\s|$)/.exec(body);
    requirements.push({ id, text: (sentence ? sentence[0] : body).trim() });
  }
  return requirements;
}

function collectTestFiles(directory: string, found: string[]): void {
  if (!fs.existsSync(directory)) return;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collectTestFiles(full, found);
    } else if (TEST_FILE.test(entry.name)) {
      found.push(full);
    }
  }
}

/**
 * Maps each requirement ID to the test files that contain an `it(...)` or
 * `test(...)` whose name starts with that ID. Paths are relative to `root`
 * with forward slashes, sorted for a stable output.
 */
export function findTestsByRequirement(root: string): Map<string, string[]> {
  const files: string[] = [];
  for (const dir of TEST_DIRECTORIES) {
    collectTestFiles(path.join(root, dir), files);
  }

  const result = new Map<string, Set<string>>();
  for (const file of files) {
    const relative = path.relative(root, file).split(path.sep).join("/");
    const content = fs.readFileSync(file, "utf8");
    for (const match of content.matchAll(TEST_NAME)) {
      const id = match[2];
      if (id === undefined) continue;
      const set = result.get(id) ?? new Set<string>();
      set.add(relative);
      result.set(id, set);
    }
  }

  return new Map(
    [...result.entries()].map(([id, set]) => [id, [...set].sort()] as [string, string[]]),
  );
}

export function screenFor(id: string): string {
  const exact = SCREEN_BY_ID[id];
  if (exact !== undefined) return exact;
  const prefix = id.split("-")[0] ?? "";
  return SCREEN_BY_PREFIX[prefix] ?? "None";
}

export function buildTraceRows(root: string): TraceRow[] {
  const spec = fs.readFileSync(path.join(root, "docs", "SPEC.md"), "utf8");
  const tests = findTestsByRequirement(root);
  return parseRequirements(spec).map((requirement) => ({
    ...requirement,
    tests: tests.get(requirement.id) ?? [],
    screen: screenFor(requirement.id),
  }));
}

/**
 * Makes text safe inside a Markdown table cell. Pipes are escaped everywhere.
 * Angle brackets are turned into entities only outside code spans, because
 * GitHub shows entities literally inside backticks but swallows raw `<tag>` text outside them.
 */
function escapeCell(text: string): string {
  return text
    .split(/(`[^`]*`)/)
    .map((part) => {
      const isCode = part.startsWith("`") && part.endsWith("`") && part.length > 1;
      const piped = part.replace(/\|/g, "\\|");
      return isCode ? piped : piped.replace(/</g, "&lt;").replace(/>/g, "&gt;");
    })
    .join("");
}

export function renderTraceMarkdown(rows: TraceRow[]): string {
  const lines: string[] = [
    "# Requirements trace",
    "",
    "Generated by `npm run trace` from `docs/SPEC.md` and the test names in the repository. Do not edit by hand.",
    "",
    "| ID | Requirement | Tests | Screen |",
    "|---|---|---|---|",
  ];

  for (const row of rows) {
    let tests: string;
    if (row.tests.length > 0) {
      tests = row.tests.map((file) => `\`${file}\``).join("<br>");
    } else if (PIPELINE_VERIFIED_IDS.includes(row.id)) {
      tests = "No unit test (verified by the pipeline and documents)";
    } else {
      tests = "**MISSING**";
    }
    lines.push(`| ${row.id} | ${escapeCell(row.text)} | ${tests} | ${escapeCell(row.screen)} |`);
  }

  const covered = rows.filter((row) => row.tests.length > 0).length;
  lines.push(
    "",
    `${rows.length} requirements, ${covered} with at least one test. ` +
      `${PIPELINE_VERIFIED_IDS.join(", ")} are verified by the pipeline and documents, so they need no unit test.`,
    "",
  );
  return lines.join("\n");
}

/** IDs that need a test but have none. */
export function findMissingTests(rows: TraceRow[]): string[] {
  return rows
    .filter((row) => row.tests.length === 0 && !PIPELINE_VERIFIED_IDS.includes(row.id))
    .map((row) => row.id);
}
